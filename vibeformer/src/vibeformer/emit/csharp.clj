        (update :usings into (:csharp/usings mapped-type))
        (with-text text)
        (apply-rule node :java.catch-clause-node/to-csharp-catch :rule-app.status/success))))

(defn- emit-try-statement [ctx node indent-level]
  (let [body-statements (mapv #(emit-statement ctx % (inc indent-level))
                              (child-nodes (:db ctx) (:db/id node) :body))
        catch-clauses (mapv #(emit-catch-clause ctx % indent-level)
                            (child-nodes (:db ctx) (:db/id node) :catch))
        finally-statements (mapv #(emit-statement ctx % (inc indent-level))
                                 (child-nodes (:db ctx) (:db/id node) :finally))
        body-result (merge-emits "\n" body-statements)
        catch-result (merge-emits "\n" catch-clauses)
        finally-result (merge-emits "\n" finally-statements)
        text (str (indent-lines indent-level "try") "\n"
                  (indent-lines indent-level "{")
                  (when (seq body-statements)
                    (str "\n" (:text body-result)))
                  "\n"
                  (indent-lines indent-level "}")
                  (when (seq catch-clauses)
                    (str "\n" (:text catch-result)))
                  (when (seq finally-statements)
                    (str "\n" (indent-lines indent-level "finally") "\n"
                         (indent-lines indent-level "{") "\n"
                         (:text finally-result) "\n"
                         (indent-lines indent-level "}"))))]
    (-> (merge-emits [body-result catch-result finally-result])
        (with-text text)
        (apply-rule node :java.try-statement-node/to-csharp-try :rule-app.status/success))))

(defn- emit-statement [ctx node indent-level]
  (case (:node/kind node)
    :java.node/local-variable
    (let [source-type (node-type-ref (:db ctx) node :local-type)
          mapped-type (map-type source-type)
          initializer (emit-child-expression ctx node :initializer)
          text (str (:csharp/type mapped-type) " " (:node/name node) " = " (:text initializer) ";")]
      (-> initializer
          (update :usings into (:csharp/usings mapped-type))
          (with-text (indent-lines indent-level text))
          (apply-rule node :java.local-variable-node/to-csharp-local :rule-app.status/success)))

    :java.node/return-statement
    (let [expr (emit-child-expression ctx node :return-expression)]
      (-> expr
          (with-text (indent-lines indent-level (str "return " (:text expr) ";")))
          (apply-rule node :java.return-statement-node/to-csharp-return :rule-app.status/success)))

    :java.node/if-statement
    (let [condition (emit-child-expression ctx node :condition)
          then-statements (mapv #(emit-statement ctx % (inc indent-level))
                                (child-nodes (:db ctx) (:db/id node) :then))
          else-statements (mapv #(emit-statement ctx % (inc indent-level))
                                (child-nodes (:db ctx) (:db/id node) :else))
          then-result (merge-emits "\n" then-statements)
          else-result (merge-emits "\n" else-statements)
          text (str (indent-lines indent-level (str "if (" (:text condition) ")")) "\n"
                    (indent-lines indent-level "{") "\n"
                    (:text then-result) "\n"
                    (indent-lines indent-level "}")
                    (when (seq else-statements)
                      (str "\n" (indent-lines indent-level "else") "\n"
                           (indent-lines indent-level "{") "\n"
                           (:text else-result) "\n"
                           (indent-lines indent-level "}"))))]
      (-> (merge-emits [condition then-result else-result])
          (with-text text)
          (apply-rule node :java.if-statement-node/to-csharp-if :rule-app.status/success)))

    :java.node/foreach-statement
    (emit-foreach-statement ctx node indent-level)

    :java.node/try-statement
    (emit-try-statement ctx node indent-level)

    :java.node/synchronized-block
    (let [lock-node (child-node (:db ctx) (:db/id node) :lock)]
      (if lock-node
        (let [lock-expression (emit-expression ctx lock-node)
              body-statements (mapv #(emit-statement ctx % (inc indent-level))
                                     (child-nodes (:db ctx) (:db/id node) :body))
              body-result (merge-emits "\n" body-statements)
              text (str (indent-lines indent-level (str "lock (" (:text lock-expression) ")")) "\n"
                        (indent-lines indent-level "{")
                        (when (seq body-statements)
                          (str "\n" (:text body-result)))
                        "\n"
                        (indent-lines indent-level "}"))]
          (-> (merge-emits [lock-expression body-result])
              (with-text text)
              (apply-rule node :java.synchronized-block-node/to-csharp-lock :rule-app.status/success)))
        (unsupported node
                     :java.synchronized-block-node/to-csharp-lock
                     {:reason :emit.reason/missing-lock-expression})))

    :java.node/throw-statement
    (let [expr (emit-throw-expression ctx node)]
      (with-text expr (indent-lines indent-level (str (:text expr) ";"))))

    :java.node/method-call
    (let [expr (emit-expression ctx node)]
      (-> expr
          (with-text (indent-lines indent-level (str (:text expr) ";")))))

    :java.node/assignment
    (let [expr (emit-assignment-expression ctx node)]
      (-> expr
          (with-text (indent-lines indent-level (str (:text expr) ";")))))

    (let [result (unsupported node :java.statement-node/to-csharp-stub {:context :statement})]
      (with-text result (indent-lines indent-level (:text result))))))

(defn- emit-body
  ([db executable-decl indent-level]
   (emit-body db executable-decl indent-level {}))
  ([db executable-decl indent-level ctx]
   (let [statements (child-nodes db (get-in executable-decl [:decl/source-node :db/id]) :body)
         ctx (assoc ctx :db db)]
     (if (seq statements)
       (merge-emits "\n" (mapv #(emit-statement ctx % indent-level) statements))
       {:text (indent-lines indent-level "throw new System.NotImplementedException();")
        :usings #{}
        :helpers #{}
        :diagnostics []
        :rule-applications []
        :provenance []}))))

(defn- emit-synchronized-method-body [db type-decl method-decl indent-level]
  (let [body (emit-body db method-decl (inc indent-level))
        mods (modifiers method-decl)
        lock-target (if (contains? mods :static)
                      (str "typeof(" (csharp-identifier (:decl/name type-decl)) ")")
                      "this")
        text (str (indent-lines indent-level (str "lock (" lock-target ")")) "\n"
                  (indent-lines indent-level "{") "\n"
                  (:text body) "\n"
                  (indent-lines indent-level "}"))]
    (-> body
        (with-text text)
        (apply-rule (:decl/source-node method-decl)
                    :java.synchronized-method/to-csharp-lock
                    :rule-app.status/success))))

(defn- inherited-types [db type-decl]
  (let [node-eid (get-in type-decl [:decl/source-node :db/id])]
    (->> (d/q '[:find ?kind (pull ?type pattern)
                :in $ ?node pattern
                :where
                [?ref :ref/from-node ?node]
                [?ref :ref/kind ?kind]
                [?ref :ref/to-type ?type]
                [(contains? #{:ref.kind/extends :ref.kind/implements} ?kind)]]
              db
              node-eid
              (type-pull-pattern))
         (sort-by (fn [[kind source-type]]
                    [(if (= :ref.kind/extends kind) 0 1) (:type/id source-type)]))
         (mapv second))))

(defn- base-list [db type-decl]
  (when-let [bases (seq (map type-name (inherited-types db type-decl)))]
    (str " : " (str/join ", " bases))))

(defn- type-line [db type-decl]
  (let [mods (modifiers type-decl)]
    (if (= :decl.kind/interface (:decl/kind type-decl))
      (str "    " (visibility mods) " interface " (:decl/name type-decl)
           (type-param-suffix type-decl)
           (base-list db type-decl)
           "\n")
      (str "    "
           (str/join " " (cond-> [(visibility mods)]
                           (contains? mods :final) (conj "sealed")
                           true (conj "class")
                           true (conj (str (:decl/name type-decl)
                                           (type-param-suffix type-decl)))))
           (base-list db type-decl)
           "\n"))))

(defn- field-line [db field-decl]
  (let [mods (modifiers field-decl)]
    (when (:decl/type field-decl)
      (let [mapped-type (map-type (:decl/type field-decl))
            initializer-node (child-node db (get-in field-decl [:decl/source-node :db/id]) :initializer)
            initializer (when initializer-node (emit-expression {:db db} initializer-node))
            field-modifiers (cond-> [(visibility mods)]
                              (contains? mods :static) (conj "static")
                              (contains? mods :final) (conj "readonly"))
            text (str "        "
                      (str/join " " (conj field-modifiers
                                          (:csharp/type mapped-type)
                                          (:decl/name field-decl)))
                      (when initializer (str " = " (:text initializer)))
                      ";\n")]
        (-> (or initializer (merge-emits []))
            (apply-type-metadata [mapped-type])
            (with-text text)
            (apply-rule (:decl/source-node field-decl)
                        :java.field-node/to-csharp-field
                        :rule-app.status/success))))))

(defn- method-name [method-decl]
  (if (= "main" (:decl/name method-decl))
    "Main"
    (:decl/name method-decl)))

(defn- signature-modifiers [decl]
  (let [mods (modifiers decl)]
    (cond-> [(visibility mods)]
      (contains? mods :static) (conj "static"))))

(def nullable-reflection-return-calls
  #{["java.lang.Class" "getGenericSuperclass"]
    ["java.lang.Class" "getComponentType"]
    ["java.lang.reflect.ParameterizedType" "getOwnerType"]})

(defn- direct-return-expression [db method-decl]
  (when-let [return-node (some #(when (= :java.node/return-statement (:node/kind %)) %)
                               (child-nodes db
                                            (get-in method-decl [:decl/source-node :db/id])
                                            :body))]
    (child-node db (:db/id return-node) :return-expression)))

(defn- nullable-reflection-return? [db method-decl]
  (when-let [expr (direct-return-expression db method-decl)]
    (when (= :java.node/method-call (:node/kind expr))
      (when-let [ref (method-call-ref db expr)]
        (contains? nullable-reflection-return-calls
                   [(get-in ref [:ref/owner-type :type/id]) (:ref/name ref)])))))

(defn- method-return-type [db method-decl]
  (cond-> (:decl/return-type method-decl)
    (nullable-reflection-return? db method-decl)
    (assoc :type/nullable? true)))

(defn- executable-signature-type-mappings [db executable-decl]
  (let [param-types (map :source-type (type-ref-params db executable-decl))]
    (->> (concat (keep identity [(when (= :decl.kind/method (:decl/kind executable-decl))
                                   (method-return-type db executable-decl))])
                 param-types)
         (map map-type)
         vec)))

(defn- apply-signature-metadata [result mapped-types]
  (apply-type-metadata result mapped-types))

(defn- method-signature [db method-decl interface?]
  (let [return-type (type-name (method-return-type db method-decl))
        prefix (if interface?
                 []
                 (signature-modifiers method-decl))]
    (str/join " " (concat prefix
                          [return-type
                           (str (method-name method-decl)
                                (type-param-suffix method-decl)
                                "(" (param-list db method-decl) ")")]))))

(defn- constructor-block [db class-name ctor-decl]
  (let [body (emit-body db ctor-decl 3)
        signature-types (executable-signature-type-mappings db ctor-decl)]
    (-> body
        (apply-signature-metadata signature-types)
        (with-text (str "        "
                        (str/join " " (conj (signature-modifiers ctor-decl) class-name))
                        "(" (param-list db ctor-decl) ")\n"
                        "        {\n"
                        (:text body) "\n"
                        "        }\n"))
        (apply-rule (:decl/source-node ctor-decl)
                    :java.constructor-node/to-csharp-constructor
                    :rule-app.status/success))))

(defn- method-block [db type-decl method-decl interface?]
  (let [signature-types (executable-signature-type-mappings db method-decl)]
    (if interface?
      (let [body-statements (child-nodes db (get-in method-decl [:decl/source-node :db/id]) :body)
          signature (method-signature db method-decl true)]
        (if (seq body-statements)
          (let [body (emit-body db method-decl 3)]
            (-> body
                (apply-signature-metadata signature-types)
                (with-text (str "        "
                                signature
                                "\n"
                                "        {\n"
                                (:text body) "\n"
                                "        }\n"))
                (apply-rule (:decl/source-node method-decl)
                            :java.method-node/to-csharp-method
                            :rule-app.status/success)))
          (-> (emitted (str "        " signature ";\n")
                       (:decl/source-node method-decl)
                       :java.method-node/to-csharp-method)
              (apply-signature-metadata signature-types))))
      (let [body (if (contains? (modifiers method-decl) :synchronized)
                   (emit-synchronized-method-body db type-decl method-decl 3)
                   (emit-body db method-decl 3))]
        (-> body
            (apply-signature-metadata signature-types)
            (with-text (str "        "
                            (method-signature db method-decl false)
                            "\n"
                            "        {\n"
                            (:text body) "\n"
                            "        }\n"))
            (apply-rule (:decl/source-node method-decl)
                        :java.method-node/to-csharp-method
                        :rule-app.status/success))))))

