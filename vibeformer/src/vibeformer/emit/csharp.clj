  [:db/id
   :decl/id
   :decl/lang
   :decl/kind
   :decl/name
   :decl/qualified-name
   :decl/modifiers
   {:decl/type (type-pull-pattern)}
   {:decl/return-type (type-pull-pattern)}
   {:decl/type-params [:type-param/id
                       :type-param/ordinal
                       :type-param/name]}
   {:decl/source-node [:db/id
                       :node/id
                       :node/kind
                       :node/name
                       :node/value
                       :node/ordinal
                       :node/start-line
                       :node/start-column
                       :node/end-line
                       :node/end-column
                       {:node/parent [:db/id
                                      :node/id]}
                       {:node/file [:file/id
                                    :file/path
                                    :file/package]}]}])

(defn- member-decls [db class-decl]
  (let [parent-eid (get-in class-decl [:decl/source-node :db/id])]
    (->> (d/q '[:find (pull ?decl pattern)
                :in $ ?parent pattern
                :where
                [?node :node/parent ?parent]
                [?decl :decl/source-node ?node]
                [?decl :decl/lang :lang/java]]
              db
              parent-eid
              (member-decl-pull-pattern))
         (map first)
         vec)))

(defn- member-groups [db class-decl]
  (group-by :decl/kind (member-decls db class-decl)))

(defn- type-ref-params [db executable-decl]
  (let [node-eid (get-in executable-decl [:decl/source-node :db/id])
        ref-pattern [:ref/role
                     :ref/source-name
                     {:ref/to-type (type-pull-pattern)}]]
    (->> (d/q '[:find (pull ?ref pattern)
                :in $ ?node pattern
                :where
                [?ref :ref/from-node ?node]
                [?ref :ref/kind :ref.kind/type-use]
                [?ref :ref/role]]
              db
              node-eid
              ref-pattern)
         (map first)
         (keep (fn [{:ref/keys [role source-name to-type]}]
                 (when (str/starts-with? (name role) "param-")
                   {:role role
                    :source-name source-name
                    :source-type to-type})))
         (sort-by (comp parse-long second #(re-matches #"param-(\d+)" (name (:role %)))))
         vec)))

(defn- param-name [index param]
  (let [source-name (:source-name param)]
    (if (str/blank? source-name)
      (str "arg" index)
      source-name)))

(defn- param-list [db executable-decl]
  (->> (type-ref-params db executable-decl)
       (map-indexed (fn [index param]
                      (str (type-name (:source-type param))
                           " "
                           (param-name index param))))
       (str/join ", ")))

(defn- node-pull-pattern []
  [:db/id
   :node/id
   :node/lang
   :node/kind
   :node/name
   :node/role
   :node/value
   :node/ordinal
   :node/start-line
   :node/start-column
   :node/end-line
   :node/end-column
   {:node/file [:file/id :file/path :file/lang]}])

(defn- child-nodes
  ([db parent-eid]
   (->> (d/q '[:find (pull ?node pattern)
               :in $ ?parent pattern
               :where [?node :node/parent ?parent]]
             db
             parent-eid
             (node-pull-pattern))
        (map first)
        (sort-by (juxt #(or (:node/ordinal %) 0) :node/id))
        vec))
  ([db parent-eid role]
   (->> (child-nodes db parent-eid)
        (filter #(= role (:node/role %)))
        vec)))

(defn- child-node [db parent-eid role]
  (first (child-nodes db parent-eid role)))

(defn- node-type-ref [db node role]
  (ffirst
   (d/q '[:find (pull ?type pattern)
          :in $ ?node ?role pattern
          :where
          [?ref :ref/from-node ?node]
          [?ref :ref/kind :ref.kind/type-use]
          [?ref :ref/role ?role]
          [?ref :ref/to-type ?type]]
        db
        (:db/id node)
        role
        (type-pull-pattern))))

(defn- parent-node [db node]
  (ffirst
   (d/q '[:find (pull ?parent pattern)
          :in $ ?node pattern
          :where
          [?node :node/parent ?parent]]
        db
        (:db/id node)
        (node-pull-pattern))))

(defn- enclosing-executable-node [db node]
  (loop [current node]
    (when-let [parent (parent-node db current)]
      (if (contains? #{:java.node/method :java.node/constructor} (:node/kind parent))
        parent
        (recur parent)))))

(defn- method-call-ref [db node]
  (ffirst
   (d/q '[:find (pull ?ref [:ref/id
                            :ref/name
                            :ref/resolved?
                            :ref/reason
                            {:ref/to-type [:type/id :type/lang :type/name :type/nullable?]}
                            {:ref/owner-type [:type/id :type/lang :type/name :type/nullable?]}
                            {:ref/to-decl [:decl/id
                                           :decl/name
                                           :decl/qualified-name
                                           {:decl/source-node [:db/id :node/id :node/kind :node/name]}]}])
          :in $ ?node
          :where
          [?ref :ref/from-node ?node]
          [?ref :ref/kind :ref.kind/method-call]]
        db
        (:db/id node))))

(defn- constructor-call-ref [db node]
  (ffirst
   (let [pattern [:ref/id
                  :ref/name
                  :ref/resolved?
                  :ref/reason
                  {:ref/to-type (type-pull-pattern)}
                  {:ref/to-decl [:decl/id
                                 :decl/name
                                 :decl/qualified-name
                                 {:decl/source-node [:db/id :node/id :node/kind :node/name]}]}]]
     (d/q '[:find (pull ?ref pattern)
            :in $ ?node pattern
            :where
            [?ref :ref/from-node ?node]
            [?ref :ref/kind :ref.kind/constructor-call]]
          db
          (:db/id node)
          pattern))))

(defn- field-access-ref [db node]
  (ffirst
   (d/q '[:find (pull ?ref [:ref/id
                            :ref/name
                            :ref/resolved?
                            :ref/reason
                            {:ref/to-type [:type/id :type/lang :type/name :type/nullable?]}
                            {:ref/owner-type [:type/id :type/lang :type/name :type/nullable?]}
                            {:ref/to-decl [:decl/id
                                           :decl/name
                                           :decl/qualified-name
                                           :decl/type
                                           :decl/modifiers
                                           {:decl/source-node [:db/id :node/id :node/kind :node/name]}]}])
          :in $ ?node
          :where
          [?ref :ref/from-node ?node]
          [?ref :ref/kind :ref.kind/field-access]]
        db
        (:db/id node))))

(defn- variable-read-type [db node]
  (when-let [name (:node/name node)]
    (when-let [executable (enclosing-executable-node db node)]
      (ffirst
       (d/q '[:find (pull ?type pattern)
              :in $ ?executable ?name pattern
              :where
              [?ref :ref/from-node ?executable]
              [?ref :ref/kind :ref.kind/type-use]
              [?ref :ref/source-name ?name]
              [?ref :ref/to-type ?type]]
            db
            (:db/id executable)
            name
            (type-pull-pattern))))))

(defn- expression-type [ctx node]
  (let [db (:db ctx)]
    (case (:node/kind node)
      :java.node/method-call
      (get-in (method-call-ref db node) [:ref/to-type])

      :java.node/object-creation
      (get-in (constructor-call-ref db node) [:ref/to-type])

      :java.node/variable-read
      (variable-read-type db node)

      :java.node/local-variable
      (node-type-ref db node :local-type)

      nil)))

(defn- first-type-arg [source-type]
  (some->> (:type/args source-type)
           (sort-by #(or (:type.arg/ordinal %) 0))
           first
           :type.arg/type))

(defn- stream-source-node [db node]
  (loop [current node]
    (when current
      (if (and (= :java.node/method-call (:node/kind current))
               (= "stream" (:node/name current)))
        (child-node db (:db/id current) :target)
        (recur (child-node db (:db/id current) :target))))))

(defn- stream-element-type [ctx node]
  (or (some->> (stream-source-node (:db ctx) node)
               (expression-type ctx)
               first-type-arg)
      {:type/lang :lang/java
       :type/name "java.lang.Object"
       :type/nullable? false}))

(defn- enum-source-type? [db source-type]
