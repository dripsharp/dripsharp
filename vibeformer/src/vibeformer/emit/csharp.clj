                 :java.type-pattern-node/to-csharp-pattern
                 {:reason :emit.reason/missing-pattern-type})))

(defn- emit-throw-expression [ctx node]
  (let [expr (emit-child-expression ctx node :thrown-expression)]
    (-> expr
        (with-text (str "throw " (:text expr)))
        (apply-rule node :java.throw-statement-node/to-csharp-throw :rule-app.status/success))))

(defn- emit-switch-arm-pattern [ctx case-node]
  (let [labels (child-nodes (:db ctx) (:db/id case-node) :case-label)]
    (if (seq labels)
      (merge-emits " or " (mapv #(emit-expression ctx %) labels))
      {:text "_"
       :usings #{}
       :helpers #{}
       :diagnostics []
       :rule-applications []
       :provenance []})))

(defn- emit-switch-arm-result [ctx node]
  (case (:node/kind node)
    :java.node/throw-statement
    (emit-throw-expression ctx node)

    (emit-expression ctx node)))

(defn- emit-switch-case-arm [ctx case-node]
  (let [results (child-nodes (:db ctx) (:db/id case-node) :case-result)]
    (if (and (= "arrow" (:node/value case-node))
             (= 1 (count results)))
      (let [pattern (emit-switch-arm-pattern ctx case-node)
            result (emit-switch-arm-result ctx (first results))
            combined (merge-emits [pattern result])
            text (str (indent 1) (:text pattern) " => " (:text result) ",\n")]
        (-> combined
            (with-text text)
            (apply-rule case-node
                        :java.switch-case-node/to-csharp-switch-arm
                        :rule-app.status/success)))
      (unsupported case-node
                   :java.switch-case-node/to-csharp-switch-arm
                   {:reason :emit.reason/unsupported-switch-case
                    :case-kind (:node/value case-node)
                    :result-count (count results)}))))

(defn- emit-switch-expression [ctx node]
  (let [selector (emit-child-expression ctx node :selector)
        cases (child-nodes (:db ctx) (:db/id node) :case)
        arms (mapv #(emit-switch-case-arm ctx %) cases)
        arms-result (merge-emits arms)
        combined (merge-emits [selector arms-result])
        text (str (:text selector) " switch\n"
                  "{\n"
                  (:text arms-result)
                  "}")]
    (-> combined
        (with-text text)
        (apply-rule node
                    :java.switch-expression-node/to-csharp-switch
                    :rule-app.status/success))))

(defn- lambda-parameters [node]
  (let [value (:node/value node)]
    (if (str/blank? value)
      []
      (str/split value #","))))

(defn- emit-lambda [ctx node]
  (if-let [body (child-node (:db ctx) (:db/id node) :body-expression)]
    (let [body-result (emit-expression ctx body)
          params (lambda-parameters node)
          param-text (case (count params)
                       0 "()"
                       1 (first params)
                       (str "(" (str/join ", " params) ")"))]
      (-> body-result
          (with-text (str param-text " => " (:text body-result)))
          (apply-rule node :java.lambda-node/to-csharp-lambda :rule-app.status/success)))
    (unsupported node
                 :java.lambda-node/to-csharp-lambda
                 {:reason :emit.reason/unsupported-lambda-body})))

(defn- emit-expression [ctx node]
  (case (:node/kind node)
    :java.node/literal
    (emitted (literal-text node) node :java.literal-node/to-csharp-literal)

    :java.node/variable-read
    (emitted (:node/name node) node :java.variable-read-node/to-csharp-variable)

    :java.node/variable-write
    (emitted (:node/name node) node :java.variable-write-node/to-csharp-variable)

    :java.node/this
    (emitted (or (:this-text ctx) "this") node :java.this-node/to-csharp-this)

    :java.node/type-access
    (emitted (csharp-type-access (:node/value node)) node :java.type-access-node/to-csharp-type)

    :java.node/type-cast
    (let [cast-type (node-type-ref (:db ctx) node :cast-type)
          mapped-type (when cast-type (map-type cast-type))
          operand (emit-child-expression ctx node :operand)]
      (if-let [target-type (:csharp/type mapped-type)]
        (-> operand
            (update :usings into (:csharp/usings mapped-type))
            (with-text (str "(" target-type ")(" (:text operand) ")"))
            (apply-rule node :java.type-cast-node/to-csharp-cast :rule-app.status/success))
        (unsupported node :java.type-cast-node/to-csharp-cast {:type (:node/value node)})))

    :java.node/type-pattern
    (emit-type-pattern ctx node)

    :java.node/field-read
    (emit-field-read ctx node)

    :java.node/field-write
    (emit-field-write ctx node)

    :java.node/assignment
    (emit-assignment-expression ctx node)

    :java.node/array-read
    (let [target (emit-child-expression ctx node :target)
          index (emit-child-expression ctx node :index)]
      (-> (merge-emits [target index])
          (with-text (str (:text target) "[" (:text index) "]"))
          (apply-rule node :java.array-read-node/to-csharp-indexer :rule-app.status/success)))

    :java.node/binary-operator
    (let [left (emit-child-expression ctx node :left)
          right (emit-child-expression ctx node :right)
          op (binary-operator (:node/value node))]
      (if op
        (-> (merge-emits [left right])
            (with-text (str (:text left) " " op " " (:text right)))
            (apply-rule node :java.binary-operator-node/to-csharp-binary :rule-app.status/success))
        (unsupported node :java.binary-operator-node/to-csharp-binary {:operator (:node/value node)})))

    :java.node/unary-operator
    (let [operand (emit-child-expression ctx node :operand)
          op (unary-operator (:node/value node))]
      (if op
        (-> operand
            (with-text (str op "(" (:text operand) ")"))
            (apply-rule node :java.unary-operator-node/to-csharp-unary :rule-app.status/success))
        (unsupported node :java.unary-operator-node/to-csharp-unary {:operator (:node/value node)})))

    :java.node/conditional-expression
    (let [condition (emit-child-expression ctx node :condition)
          then-expression (emit-child-expression ctx node :then-expression)
          else-expression (emit-child-expression ctx node :else-expression)]
      (-> (merge-emits [condition then-expression else-expression])
          (with-text (str (:text condition)
                          " ? " (:text then-expression)
                          " : " (:text else-expression)))
          (apply-rule node :java.conditional-expression-node/to-csharp-conditional :rule-app.status/success)))

    :java.node/lambda
    (emit-lambda ctx node)

    :java.node/method-reference
    (if (and (= "new" (:node/name node))
             (node-type-ref (:db ctx) node :method-reference-target-type))
      (let [target-type (node-type-ref (:db ctx) node :method-reference-target-type)
            mapped (map-type target-type)]
        (-> (emitted (:csharp/type mapped) node :java.stream-collector-to-collection/to-csharp-collection-constructor)
            (update :usings into (:csharp/usings mapped))))
      (unsupported node
                   :java.stream-collector-to-collection/to-csharp-collection-constructor
                   {:reason :emit.reason/unsupported-method-reference}))

    :java.node/switch-expression
    (emit-switch-expression ctx node)

    :java.node/method-call
    (emit-method-call ctx node)

    :java.node/object-creation
    (emit-object-creation ctx node)

    (unsupported node :java.expression-node/to-csharp-stub {:context :expression})))

(defn- indent [level]
  (apply str (repeat level "    ")))

(defn- indent-lines [level text]
  (let [prefix (indent level)]
    (->> (str/split-lines text)
         (map #(str prefix %))
         (str/join "\n"))))

(defn- emit-foreach-statement [ctx node indent-level]
  (let [source-type (node-type-ref (:db ctx) node :element-type)
        mapped-type (map-type source-type)
        iterable (emit-child-expression ctx node :iterable)
        body-statements (mapv #(emit-statement ctx % (inc indent-level))
                              (child-nodes (:db ctx) (:db/id node) :body))
        body-result (merge-emits "\n" body-statements)
        text (str (indent-lines indent-level
                                (str "foreach (" (:csharp/type mapped-type)
                                     " " (csharp-identifier (:node/name node))
                                     " in " (:text iterable) ")"))
                  "\n"
                  (indent-lines indent-level "{")
                  (when (seq body-statements)
                    (str "\n" (:text body-result)))
                  "\n"
                  (indent-lines indent-level "}"))]
    (-> (merge-emits [iterable body-result])
        (update :usings into (:csharp/usings mapped-type))
        (with-text text)
        (apply-rule node :java.foreach-statement-node/to-csharp-foreach :rule-app.status/success))))

(defn- emit-catch-clause [ctx node indent-level]
