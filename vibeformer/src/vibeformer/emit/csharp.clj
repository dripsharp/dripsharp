(defn- kotlin-top-level-member-decls [db]
  (let [decl-source-node-ids (->> (d/q '[:find ?node
                                         :where [_ :decl/source-node ?node]]
                                       db)
                                  (map first)
                                  set)]
    (->> (d/q '[:find (pull ?decl pattern)
                :in $ pattern
                :where
                [?decl :decl/lang :lang/kotlin]
                [?decl :decl/kind ?kind]
                [(contains? #{:decl.kind/function :decl.kind/property} ?kind)]]
              db
              (member-decl-pull-pattern))
         (map first)
         (filter #(not (contains? decl-source-node-ids
                                  (get-in % [:decl/source-node :node/parent :db/id]))))
         (sort-by (juxt #(get-in % [:decl/source-node :node/file :file/id])
                        #(get-in % [:decl/source-node :node/ordinal])
                        :decl/name))
         vec)))

(defn- file-base-name [file-path]
  (-> (str file-path)
      (str/split #"/")
      last
      (str/replace #"\.[^.]+$" "")))

(defn- facade-base-name [file-path]
  (str (csharp-file-name (file-base-name file-path)) "Kt"))

(defn- short-stable-suffix [value]
  (subs (sha256 value) 7 15))

(defn- facade-key [file]
  [(:file/package file) (facade-base-name (:file/path file))])

(defn- facade-name [file-id file file-counts]
  (let [base (facade-base-name (:file/path file))]
    (if (> (get file-counts (facade-key file) 0) 1)
      (str base "_" (short-stable-suffix file-id))
      base)))

(defn- kotlin-file-facades [db]
  (let [members (kotlin-top-level-member-decls db)
        grouped (group-by #(get-in % [:decl/source-node :node/file :file/id]) members)
        base-counts (->> grouped
                         vals
                         (map (comp facade-key :node/file :decl/source-node first))
                         frequencies)]
    (->> grouped
         (map (fn [[file-id file-members]]
                (let [file (get-in (first file-members) [:decl/source-node :node/file])
                      namespace (:file/package file)
                      name (facade-name file-id file base-counts)
                      node-id (str file-id ":file-facade:" name)]
                  {:decl/lang :lang/kotlin
                   :decl/kind :decl.kind/file-facade
                   :decl/name name
                   :decl/qualified-name (if (str/blank? namespace)
                                          name
                                          (str namespace "." name))
                   :decl/source-node {:node/id node-id
                                      :node/kind :kotlin.node/file-facade
                                      :node/name name
                                      :node/file file}
                   :kotlin.file-facade/members (vec file-members)})))
         (sort-by :decl/qualified-name)
         vec)))

(defn- source-type-decls [db]
  (vec (sort-by (juxt :decl/lang :decl/qualified-name)
                (concat (type-decls db)
                        (kotlin-type-decls db)
                        (kotlin-file-facades db)))))

(defn- type-pull-pattern
  ([] (type-pull-pattern 6))
  ([depth]
   (cond-> [:type/id
            :type/lang
            :type/name
            :type/nullable?]
     (pos? depth)
     (conj {:type/args [:type.arg/ordinal
                        {:type.arg/type (type-pull-pattern (dec depth))}]}))))

