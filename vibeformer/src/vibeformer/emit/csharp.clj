(defn- unsupported-declaration [decl rule reason]
  (apply-rule {:text ""
               :usings #{}
               :helpers #{}
               :diagnostics [(assoc (source-context (:decl/source-node decl))
                                    :diagnostic/severity :diagnostic.severity/error
                                    :diagnostic/message "Unsupported Java enum member"
                                    :rule/id rule
                                    :rule/context {:reason reason})]
               :rule-applications []
               :provenance []}
              (:decl/source-node decl)
              rule
              :rule-app.status/failed))

(defn- bool-return-type? [method-decl]
  (= "bool" (type-name (:decl/return-type method-decl))))

(defn- bool-literal-node? [node]
  (and (= :java.node/literal (:node/kind node))
       (boolean? (edn/read-string (:node/value node)))))

(defn- enum-switch-case-supported? [db case-node]
  (let [labels (child-nodes db (:db/id case-node) :case-label)
        results (child-nodes db (:db/id case-node) :case-result)]
    (and (= "arrow" (:node/value case-node))
         (= 1 (count results))
         (every? #(= :java.node/field-read (:node/kind %)) labels)
         (bool-literal-node? (first results)))))

(defn- enum-switch-method-shape [db method-decl]
  (let [statements (child-nodes db (get-in method-decl [:decl/source-node :db/id]) :body)
        return-node (first statements)
        switch-node (when (= :java.node/return-statement (:node/kind return-node))
                      (child-node db (:db/id return-node) :return-expression))
        selector (when (= :java.node/switch-expression (:node/kind switch-node))
                   (child-node db (:db/id switch-node) :selector))
        cases (when switch-node
                (child-nodes db (:db/id switch-node) :case))
        mods (modifiers method-decl)]
    (when (and (contains? mods :public)
               (not (contains? mods :static))
               (bool-return-type? method-decl)
               (= 1 (count statements))
               (= :java.node/this (:node/kind selector))
               (seq cases)
               (every? #(enum-switch-case-supported? db %) cases))
      {:return return-node
       :switch switch-node
       :cases cases})))

(defn- enum-constant? [enum-decl field-decl]
  (let [mods (modifiers field-decl)]
    (and (= (:decl/qualified-name enum-decl)
            (get-in field-decl [:decl/type :type/name]))
         (contains? mods :static)
         (contains? mods :final))))

(defn- enum-constant-line [field-decl final?]
  (emitted (str "        " (:decl/name field-decl) (if final? "\n" ",\n"))
           (:decl/source-node field-decl)
           :java.field-node/to-csharp-field))

(defn- stateful-enum? [stateful-fields enum-ctors]
  (or (seq stateful-fields)
      (seq enum-ctors)))

(defn- stateful-enum-constructor-block [db enum-decl ctor-decl]
  (let [body (emit-body db ctor-decl 3)]
    (-> body
        (with-text (str "        private " (:decl/name enum-decl)
                        "(" (param-list db ctor-decl) ")\n"
                        "        {\n"
                        (:text body) "\n"
                        "        }\n"))
        (apply-rule (:decl/source-node ctor-decl)
                    :java.constructor-node/to-csharp-constructor
                    :rule-app.status/success))))

(defn- stateful-enum-content [db enum-decl constants stateful-fields enum-ctors enum-methods]
  (let [namespace (csharp-namespace enum-decl)
        static-instances (->> constants
                              (mapv #(field-line db %)))
        fields (->> stateful-fields
                    (mapv #(field-line db %)))
        ctors (mapv #(stateful-enum-constructor-block db enum-decl %) enum-ctors)
        method-shapes (mapv (fn [method-decl]
                              [method-decl
                               (let [result (method-block db enum-decl method-decl false)]
                                 (when (empty? (:diagnostics result))
                                   result))])
                            enum-methods)
        supported-methods (->> method-shapes (keep second) vec)
        unsupported-methods (->> method-shapes
                                 (remove second)
                                 (map first)
                                 vec)
        unsupported-members (mapv #(unsupported-declaration %
                                                            :java.method-node/to-csharp-method
                                                            :emit.reason/unsupported-enum-method)
                                  unsupported-methods)
        body-sections (->> [static-instances fields ctors supported-methods]
                           (remove empty?)
                           (mapv #(merge-emits "\n" %)))
        body-metadata (merge-emits "\n\n" body-sections)
        content-metadata (merge-emits (concat [body-metadata] unsupported-members))
        all-usings (->> (:usings content-metadata)
                        (map csharp-qualified-name)
                        (remove #(= namespace %))
                        set
                        sort
                        vec)
        text (str generated-file-header
                  (when (seq all-usings)
                    (str (str/join "\n" (map #(str "using " % ";") all-usings)) "\n\n"))
                  (when-not (str/blank? namespace)
                    (str "namespace " namespace "\n{\n"))
                  "    " (visibility (modifiers enum-decl)) " sealed class " (:decl/name enum-decl) "\n"
                  "    {\n"
                  (:text content-metadata)
                  (when (seq (:text content-metadata)) "\n")
                  "    }\n"
                  (when-not (str/blank? namespace)
                    "}\n"))]
    (-> content-metadata
        (with-text text)
        (apply-rule (:decl/source-node enum-decl)
                    :java.enum-node/to-csharp-enum
                    :rule-app.status/success))))

(defn- enum-switch-arm-pattern [db enum-decl case-node]
  (let [labels (child-nodes db (:db/id case-node) :case-label)]
    (if (seq labels)
      (->> labels
           (map #(str (:decl/name enum-decl) "." (:node/name %)))
           (str/join " or "))
      "_")))

(defn- enum-switch-case-arm [db enum-decl case-node]
  (let [result-node (first (child-nodes db (:db/id case-node) :case-result))
        result (emit-expression {:db db} result-node)
        text (str (indent 4)
                  (enum-switch-arm-pattern db enum-decl case-node)
                  " => "
                  (:text result)
                  ",\n")]
    (-> result
        (with-text text)
        (apply-rule case-node
                    :java.switch-case-node/to-csharp-switch-arm
                    :rule-app.status/success))))

(defn- enum-switch-expression [db enum-decl switch-node cases]
  (let [arms (mapv #(enum-switch-case-arm db enum-decl %) cases)
        arms-result (merge-emits arms)
        text (str "value switch\n"
                  (indent 3) "{\n"
                  (:text arms-result)
                  (indent 3) "}")]
    (-> arms-result
        (with-text text)
        (apply-rule switch-node
                    :java.switch-expression-node/to-csharp-switch
                    :rule-app.status/success))))

(defn- enum-extension-signature [db enum-decl method-decl]
  (let [params (param-list db method-decl)]
    (str "public static "
         (type-name (:decl/return-type method-decl))
         " "
         (method-name method-decl)
         "(this "
         (:decl/name enum-decl)
         " value"
         (when-not (str/blank? params)
           (str ", " params))
         ")")))

(defn- enum-switch-extension-method [db enum-decl method-decl shape]
  (let [switch-result (enum-switch-expression db enum-decl (:switch shape) (:cases shape))
        signature (enum-extension-signature db enum-decl method-decl)
        text (str "        " signature "\n"
                  "        {\n"
                  (indent 3) "return " (:text switch-result) ";\n"
                  "        }\n")]
    (-> switch-result
        (with-text text)
        (apply-rule (:decl/source-node method-decl)
                    :java.method-node/to-csharp-method
                    :rule-app.status/success))))

(defn- descendant-nodes [db root-eid]
  (loop [queue (child-nodes db root-eid)
         result []]
    (if-let [node (first queue)]
      (recur (into (vec (rest queue)) (child-nodes db (:db/id node)))
             (conj result node))
      result)))

(defn- stateful-enum-field-read? [db stateful-field-names node]
  (let [target (child-node db (:db/id node) :target)]
    (and (= :java.node/field-read (:node/kind node))
         (contains? stateful-field-names (:node/name node))
         (or (nil? target)
             (= :java.node/this (:node/kind target))))))

(defn- enum-body-extension-method [db enum-decl method-decl stateful-field-names]
  (let [mods (modifiers method-decl)
        stateful-read? (some #(stateful-enum-field-read? db stateful-field-names %)
                             (descendant-nodes db (get-in method-decl [:decl/source-node :db/id])))]
    (when (and (contains? mods :public)
               (not (contains? mods :static))
               (not stateful-read?))
      (let [body (emit-body db method-decl 3 {:this-text "value"})
            signature (enum-extension-signature db enum-decl method-decl)]
        (when (empty? (:diagnostics body))
          (-> body
              (with-text (str "        " signature "\n"
                              "        {\n"
                              (:text body) "\n"
                              "        }\n"))
              (apply-rule (:decl/source-node method-decl)
                          :java.method-node/to-csharp-method
                          :rule-app.status/success)))))))

(defn- enum-extension-content [db enum-decl method-shapes]
  (when (seq method-shapes)
    (let [methods (mapv (fn [[method-decl shape]]
                          (if (= :enum.method/switch (:kind shape))
                            (enum-switch-extension-method db enum-decl method-decl shape)
                            (:result shape)))
                        method-shapes)
          method-result (merge-emits "\n" methods)
          text (str "\n"
                    "    public static class " (:decl/name enum-decl) "Extensions\n"
                    "    {\n"
                    (:text method-result)
                    "\n"
                    "    }\n")]
      (with-text method-result text))))

(defn- enum-content [db enum-decl]
  (let [namespace (csharp-namespace enum-decl)
        members (member-groups db enum-decl)
        constants (->> (get members :decl.kind/field)
                       (filter #(enum-constant? enum-decl %))
                       (sort-by (juxt #(get-in % [:decl/source-node :node/ordinal]) :decl/name))
                       vec)
        stateful-fields (->> (get members :decl.kind/field)
                             (remove #(enum-constant? enum-decl %))
                             (sort-by (juxt #(get-in % [:decl/source-node :node/ordinal]) :decl/name))
                             vec)
        enum-ctors (->> (get members :decl.kind/constructor)
                        (filter #(seq (type-ref-params db %)))
                        (sort-by (juxt #(get-in % [:decl/source-node :node/ordinal]) :decl/name))
                        vec)
        stateful-field-names (set (map :decl/name stateful-fields))
        enum-methods (->> (get members :decl.kind/method)
                          (sort-by (juxt #(get-in % [:decl/source-node :node/ordinal]) :decl/name))
                          vec)
        method-shapes (->> enum-methods
                           (map (fn [method-decl]
                                  [method-decl
                                   (if-let [switch-shape (enum-switch-method-shape db method-decl)]
                                     (assoc switch-shape :kind :enum.method/switch)
                                     (when-let [body-result (enum-body-extension-method db enum-decl method-decl stateful-field-names)]
                                       {:kind :enum.method/body
                                        :result body-result}))])))
        supported-methods (->> method-shapes
                               (filter second)
                               vec)
        unsupported-methods (->> method-shapes
                                 (remove second)
                                 (map first)
                                 vec)
        constant-lines (mapv (fn [field-decl index]
                               (enum-constant-line field-decl (= index (dec (count constants)))))
                             constants
                             (range))
        unsupported-members (mapv #(unsupported-declaration %
                                                            :java.method-node/to-csharp-method
                                                            :emit.reason/unsupported-enum-method)
                                  unsupported-methods)
        unsupported-fields (mapv #(unsupported-declaration %
                                                           :java.field-node/to-csharp-field
                                                           :emit.reason/unsupported-stateful-enum-field)
                                 stateful-fields)
        unsupported-ctors (mapv #(unsupported-declaration %
                                                          :java.constructor-node/to-csharp-constructor
                                                          :emit.reason/unsupported-enum-constructor)
                                enum-ctors)
        body-metadata (merge-emits constant-lines)
        body (:text body-metadata)
        enum-section (with-text body-metadata
                       (str "    " (visibility (modifiers enum-decl)) " enum " (:decl/name enum-decl) "\n"
                            "    {\n"
                            body
                            (when (seq body) "\n")
                            "    }\n"))
        extension-section (enum-extension-content db enum-decl supported-methods)
        content-metadata (merge-emits (concat [enum-section]
                                              (when extension-section
                                                [extension-section])
                                              unsupported-fields
                                              unsupported-ctors
                                              unsupported-members))
        text (str generated-file-header
                  (when-not (str/blank? namespace)
                    (str "namespace " namespace "\n{\n"))
                  (:text content-metadata)
                  (when-not (str/blank? namespace)
                    "}\n"))]
    (if (stateful-enum? stateful-fields enum-ctors)
      (stateful-enum-content db enum-decl constants stateful-fields enum-ctors enum-methods)
      (-> content-metadata
          (with-text text)
          (apply-rule (:decl/source-node enum-decl)
                      :java.enum-node/to-csharp-enum
                      :rule-app.status/success)))))

(defn- record-content [db record-decl]
  (let [namespace (csharp-namespace record-decl)
        members (member-groups db record-decl)
        components (emitted-record-components (get members :decl.kind/record-component))
        methods (emitted-method-decls db record-decl members false)
        components-metadata (merge-emits ", " components)
        methods-metadata (merge-emits "\n" methods)
        content-metadata (merge-emits [components-metadata methods-metadata])
        all-usings (->> (:usings content-metadata)
                        (map csharp-qualified-name)
                        (remove #(= namespace %))
                        set
                        sort
                        vec)
        text (str generated-file-header
                  (when (seq all-usings)
                    (str (str/join "\n" (map #(str "using " % ";") all-usings)) "\n\n"))
                  (when-not (str/blank? namespace)
                    (str "namespace " namespace "\n{\n"))
                  "    " (visibility (modifiers record-decl)) " sealed record "
                  (:decl/name record-decl)
                  "(" (:text components-metadata) ")\n"
                  "    {\n"
                  (:text methods-metadata)
                  (when (seq (:text methods-metadata)) "\n")
                  "    }\n"
                  (when-not (str/blank? namespace)
                    "}\n"))]
    (-> content-metadata
        (with-text text)
        (apply-rule (:decl/source-node record-decl)
                    :java.record-node/to-csharp-record
                    :rule-app.status/success))))

(defn- annotation-property-line [method-decl]
  (let [mapped (map-type (:decl/return-type method-decl))]
    (emitted (str "        public "
                  (:csharp/type mapped)
                  " "
                  (:decl/name method-decl)
                  " { get; init; } = default!;\n")
             (:decl/source-node method-decl)
             :java.method-node/to-csharp-method
             {:usings (:csharp/usings mapped)
              :helpers (:csharp/helpers mapped)
              :diagnostics (:csharp/diagnostics mapped)})))

(defn- annotation-content [db annotation-decl]
  (let [namespace (csharp-namespace annotation-decl)
        members (member-groups db annotation-decl)
        properties (->> (get members :decl.kind/method)
                        (sort-by (juxt #(get-in % [:decl/source-node :node/ordinal]) :decl/name))
                        (mapv annotation-property-line))
        body-metadata (merge-emits properties)
        text (str generated-file-header
                  "using System;\n\n"
                  (when-not (str/blank? namespace)
                    (str "namespace " namespace "\n{\n"))
                  "    [AttributeUsage(AttributeTargets.All)]\n"
                  "    " (visibility (modifiers annotation-decl)) " sealed class "
                  (:decl/name annotation-decl) "Attribute : Attribute\n"
                  "    {\n"
                  (:text body-metadata)
                  "    }\n"
                  (when-not (str/blank? namespace)
                    "}\n"))]
    (-> body-metadata
        (update :usings conj "System")
        (with-text text)
        (apply-rule (:decl/source-node annotation-decl)
                    :java.annotation-node/to-csharp-attribute
                    :rule-app.status/success))))

(defn- declaration-usings [db namespace type-decl members]
  (let [field-types (keep :decl/type (get members :decl.kind/field))
        record-component-types (keep :decl/type (get members :decl.kind/record-component))
        method-return-types (keep :decl/return-type (get members :decl.kind/method))
        inherited (inherited-types db type-decl)
        param-types (mapcat #(map :source-type (type-ref-params db %))
                            (concat (get members :decl.kind/constructor)
                                    (get members :decl.kind/method)))]
    (->> (concat inherited field-types record-component-types method-return-types param-types)
         (mapcat (comp :csharp/usings map-type))
         (map csharp-qualified-name)
         (remove #(= namespace %))
         set
         sort
         vec)))

(defn- class-content [db class-decl]
  (let [namespace (csharp-namespace class-decl)
        interface? (= :decl.kind/interface (:decl/kind class-decl))
        members (member-groups db class-decl)
        inherited-mappings (type-mapping-summary (inherited-types db class-decl))
        usings (declaration-usings db namespace class-decl members)
        fields (emitted-field-decls db members)
        ctors (when-not interface?
                (emitted-ctor-decls db (:decl/name class-decl) members))
        methods (emitted-method-decls db class-decl members interface?)
        body-sections (->> [fields ctors methods]
                           (remove empty?)
                           (mapv #(merge-emits "\n" %)))
        body-metadata (merge-emits "\n\n" body-sections)
        body (:text body-metadata)
        all-usings (->> (concat usings (:usings body-metadata))
                        (map csharp-qualified-name)
                        (remove #(= namespace %))
                        set
                        sort
                        vec)
        text (str generated-file-header
                  (when (seq all-usings)
                    (str (str/join "\n" (map #(str "using " % ";") all-usings)) "\n\n"))
                  (when-not (str/blank? namespace)
                    (str "namespace " namespace "\n{\n"))
                  (type-line db class-decl)
                  "    {\n"
                  body
                  (when (seq body) "\n")
                  "    }\n"
                  (when-not (str/blank? namespace)
                    "}\n"))]
    (-> body-metadata
        (apply-type-metadata inherited-mappings)
        (with-text text)
        (apply-rule (:decl/source-node class-decl)
                    (if interface?
                      :java.interface-node/to-csharp-interface
                      :java.class-node/to-csharp-class)
                    :rule-app.status/success))))

(defn- kotlin-member-decls [db type-decl]
  (let [parent-eid (get-in type-decl [:decl/source-node :db/id])]
    (->> (d/q '[:find (pull ?decl pattern)
                :in $ ?parent pattern
                :where
                [?node :node/parent ?parent]
                [?decl :decl/source-node ?node]
                [?decl :decl/lang :lang/kotlin]]
              db
              parent-eid
              (member-decl-pull-pattern))
         (map first)
         (sort-by (juxt :decl/kind :decl/name :decl/id))
         vec)))

(defn- kotlin-interface? [type-decl]
  (= :decl.kind/interface (:decl/kind type-decl)))

(defn- kotlin-file-facade? [type-decl]
  (= :decl.kind/file-facade (:decl/kind type-decl)))

(defn- kotlin-singleton-object? [db type-decl]
  (and (= :decl.kind/object (:decl/kind type-decl))
       (seq (inherited-types db type-decl))))

(defn- kotlin-static? [db type-decl]
  (or (kotlin-file-facade? type-decl)
      (and (= :decl.kind/object (:decl/kind type-decl))
           (not (kotlin-singleton-object? db type-decl)))))

(defn- kotlin-default-return [return-type]
  (when-not (= "void" (type-name return-type))
    "return default!;"))

(defn- kotlin-body-nodes [db function-decl kind]
  (let [parent-eid (get-in function-decl [:decl/source-node :db/id])]
    (->> (child-nodes db parent-eid)
         (filter #(= kind (:node/kind %)))
         (sort-by (juxt #(or (:node/ordinal %) 0) :node/id))
         vec)))

(defn- trim-blank-edges [lines]
  (let [lines (vec lines)
        lines (subvec lines (or (first (keep-indexed (fn [idx line]
                                                       (when-not (str/blank? line) idx))
                                                     lines))
                                0))
        end (or (last (keep-indexed (fn [idx line]
                                      (when-not (str/blank? line) idx))
                                    lines))
                -1)]
    (if (neg? end)
      []
      (subvec lines 0 (inc end)))))

(defn- common-indent [lines]
  (if-let [indents (seq (map #(count (re-find #"^\s*" %))
                             (remove str/blank? lines)))]
    (apply min indents)
    0))

(defn- kotlin-trim-indent-literal [value]
  (when-let [[_ body] (re-matches #"(?s)\"\"\"(.*)\"\"\"\.trimIndent\(\)" value)]
    (let [lines (trim-blank-edges (str/split (str/replace body "\r\n" "\n") #"\n" -1))
          indent (common-indent lines)]
      (->> lines
           (map #(subs % (min indent (count %))))
           (str/join "\n")))))

(declare emit-kotlin-expression)

(defn- kotlin-string-literal-text [node]
  (let [value (:node/value node)]
    (if-let [trimmed (kotlin-trim-indent-literal (str value ".trimIndent()"))]
      (csharp-string trimmed)
      value)))

(defn- emit-kotlin-child-expression [ctx node role]
  (if-let [child (child-node (:db ctx) (:db/id node) role)]
    (emit-kotlin-expression ctx child)
    (unsupported node :kotlin.expression-node/to-csharp-stub {:missing-role role})))

(defn- emit-kotlin-arguments [ctx node]
  (merge-emits ", " (mapv #(emit-kotlin-expression ctx %)
                          (child-nodes (:db ctx) (:db/id node) :argument))))

(defn- emit-kotlin-binary-expression [ctx node]
  (let [left (emit-kotlin-child-expression ctx node :left)
        right (emit-kotlin-child-expression ctx node :right)]
    (case (:node/value node)
      "+" (-> (merge-emits [left right])
              (with-text (str (:text left) " + " (:text right)))
              (apply-rule node :kotlin.binary-expression-node/to-csharp-binary :rule-app.status/success))
      (unsupported node
                   :kotlin.binary-expression-node/to-csharp-binary
                   {:operator (:node/value node)}))))

(defn- kotlin-safe-let-shape [db node]
  (let [receiver (child-node db (:db/id node) :receiver)
        selector (child-node db (:db/id node) :selector)]
    (when (and (= :kotlin.node/safe-call (:node/kind node))
               (= :kotlin.node/call-expression (:node/kind selector))
               (= "let" (:node/name selector)))
      {:receiver receiver
       :lambda (child-node db (:db/id selector) :lambda)})))

(defn- emit-kotlin-lambda-body [ctx lambda-node receiver-text]
  (if-let [body (child-node (:db ctx) (:db/id lambda-node) :body-expression)]
    (emit-kotlin-expression (assoc ctx :lambda-it receiver-text) body)
    (unsupported lambda-node :kotlin.lambda-expression-node/to-csharp-lambda {:reason :emit.reason/unsupported-lambda-body})))

(defn- emit-kotlin-elvis-expression [ctx node]
  (let [left-node (child-node (:db ctx) (:db/id node) :left)
        right (emit-kotlin-child-expression ctx node :right)]
    (if-let [{:keys [receiver lambda]} (some->> left-node (kotlin-safe-let-shape (:db ctx)))]
      (let [receiver-result (emit-kotlin-expression ctx receiver)
            lambda-result (emit-kotlin-lambda-body ctx lambda (:text receiver-result))]
        (-> (merge-emits [receiver-result lambda-result right])
            (with-text (str (:text receiver-result)
                            " is not null ? "
                            (:text lambda-result)
                            " : "
                            (:text right)))
            (apply-rule node :kotlin.elvis-expression-node/to-csharp-coalesce :rule-app.status/success)))
      (let [left (emit-kotlin-child-expression ctx node :left)]
        (-> (merge-emits [left right])
            (with-text (str (:text left) " ?? " (:text right)))
            (apply-rule node :kotlin.elvis-expression-node/to-csharp-coalesce :rule-app.status/success))))))

(defn- emit-kotlin-path-resolve [ctx receiver-node selector-node]
  (when (and (= :kotlin.node/call-expression (:node/kind selector-node))
             (= "resolve" (:node/name selector-node)))
    (let [receiver (emit-kotlin-expression ctx receiver-node)
          args (emit-kotlin-arguments ctx selector-node)]
      (-> (merge-emits [receiver args])
          (with-text (str "System.IO.Path.Combine(" (:text receiver)
                          (when (seq (:text args)) (str ", " (:text args)))
                          ")"))
          (apply-rule selector-node :kotlin.call-expression-node/to-csharp-expression :rule-app.status/success)))))

(defn- emit-kotlin-qualified-expression [ctx node]
  (let [receiver-node (child-node (:db ctx) (:db/id node) :receiver)
        selector-node (child-node (:db ctx) (:db/id node) :selector)]
    (cond
      (and (= :kotlin.node/call-expression (:node/kind selector-node))
           (= "trimIndent" (:node/name selector-node)))
      (let [receiver (emit-kotlin-expression ctx receiver-node)]
        (-> receiver
            (with-text (:text receiver))
            (apply-rule node :kotlin.qualified-expression-node/to-csharp-call :rule-app.status/success)))

      (and (= :kotlin.node/call-expression (:node/kind selector-node))
           (= "toUri" (:node/name selector-node)))
      (let [path (or (emit-kotlin-path-resolve ctx
                                               (child-node (:db ctx) (:db/id receiver-node) :receiver)
                                               (child-node (:db ctx) (:db/id receiver-node) :selector))
                     (emit-kotlin-expression ctx receiver-node))]
        (-> path
            (update :usings conj "System")
            (with-text (str "new Uri(" (:text path) ", UriKind.RelativeOrAbsolute)"))
            (apply-rule node :kotlin.qualified-expression-node/to-csharp-call :rule-app.status/success)))

      :else
      (let [receiver (emit-kotlin-expression ctx receiver-node)
            selector (emit-kotlin-expression ctx selector-node)]
        (-> (merge-emits [receiver selector])
            (with-text (str (:text receiver) "." (:text selector)))
            (apply-rule node :kotlin.qualified-expression-node/to-csharp-call :rule-app.status/success))))))

(defn- emit-kotlin-call-expression [ctx node]
  (case (:node/name node)
    "URI"
    (let [args (emit-kotlin-arguments ctx node)]
      (-> args
          (update :usings conj "System")
          (with-text (str "new Uri(" (:text args) ")"))
          (apply-rule node :kotlin.call-expression-node/to-csharp-expression :rule-app.status/success)))

    "listOf"
    (let [args (emit-kotlin-arguments ctx node)
          collection-type (or (:expected-type ctx) "List<object>")]
      (-> args
          (update :usings conj "System.Collections.Generic")
          (with-text (str "new " collection-type " { " (:text args) " }"))
          (apply-rule node :kotlin.call-expression-node/to-csharp-expression :rule-app.status/success)))

    (unsupported node
                 :kotlin.call-expression-node/to-csharp-expression
                 {:call/name (:node/name node)})))

(defn- emit-kotlin-expression [ctx node]
  (case (:node/kind node)
    :kotlin.node/string-literal
    (emitted (kotlin-string-literal-text node) node :kotlin.string-literal-node/to-csharp-literal)

    :kotlin.node/literal
    (emitted (:node/value node) node :kotlin.literal-node/to-csharp-literal)

    :kotlin.node/name-reference
    (emitted (if (and (= "it" (:node/name node)) (:lambda-it ctx))
               (:lambda-it ctx)
               (:node/name node))
             node
             :kotlin.name-reference-node/to-csharp-variable)

    :kotlin.node/binary-expression
    (emit-kotlin-binary-expression ctx node)

    :kotlin.node/elvis-expression
    (emit-kotlin-elvis-expression ctx node)

    :kotlin.node/qualified-expression
    (emit-kotlin-qualified-expression ctx node)

    :kotlin.node/call-expression
    (emit-kotlin-call-expression ctx node)

    :kotlin.node/lambda-expression
    (if-let [body (child-node (:db ctx) (:db/id node) :body-expression)]
      (let [body-result (emit-kotlin-expression ctx body)]
        (-> body-result
            (with-text (str "it => " (:text body-result)))
            (apply-rule node :kotlin.lambda-expression-node/to-csharp-lambda :rule-app.status/success)))
      (unsupported node :kotlin.lambda-expression-node/to-csharp-lambda {:reason :emit.reason/unsupported-lambda-body}))

    (unsupported node :kotlin.expression-node/to-csharp-stub {:context :kotlin-expression})))

(defn- kotlin-local-property-content [db node]
  (let [initializer-node (child-node db (:db/id node) :initializer)
        initializer (if initializer-node
                      (emit-kotlin-expression {:db db} initializer-node)
                      (emitted "default!" node :kotlin.expression-node/to-csharp-stub))]
    (-> initializer
        (with-text (str "            var " (:node/name node) " = " (:text initializer) ";\n"))
        (apply-rule node :kotlin.local-property-node/to-csharp-local :rule-app.status/success))))

(defn- kotlin-return-content [db return-type node]
  (let [return-expression (child-node db (:db/id node) :return-expression)
        result (when return-expression
                 (emit-kotlin-expression {:db db
                                          :expected-type (some-> return-type type-name)}
                                         return-expression))]
    (if result
      (-> result
          (with-text (str "            return " (:text result) ";\n"))
          (apply-rule node :kotlin.return-node/to-csharp-return :rule-app.status/success))
      (emitted "            return default!;\n"
               node
               :kotlin.return-node/to-csharp-return))))

(defn- kotlin-throw-content [db node]
  (let [thrown-expression (child-node db (:db/id node) :thrown-expression)]
    (if (and thrown-expression
             (= :kotlin.node/call-expression (:node/kind thrown-expression))
             (= "NotImplementedError" (:node/name thrown-expression)))
      (emitted "            throw new NotImplementedException();\n"
               node
               :kotlin.throw-node/to-csharp-throw
               {:usings #{"System"}})
      (unsupported node
                   :kotlin.throw-node/to-csharp-throw
                   {:throw/expression (:node/value thrown-expression)}))))

(defn- kotlin-expression-text [value]
  (cond
    (nil? value) "default!"
    (re-matches #"(?s)\".*\"" value) value
    (#{"true" "false"} value) value
    (re-matches #"-?\d+(\.\d+)?" value) value
    :else "default!"))

(defn- kotlin-function-body-content [db function-decl return-type]
  (let [locals (kotlin-body-nodes db function-decl :kotlin.node/local-property)
        returns (kotlin-body-nodes db function-decl :kotlin.node/return)
        throws (kotlin-body-nodes db function-decl :kotlin.node/throw)
        expression-body (child-node db (get-in function-decl [:decl/source-node :db/id]) :expression-body)]
    (if (or (seq locals) (seq returns) (seq throws))
      (merge-emits "\n"
                   (concat (map #(kotlin-local-property-content db %) locals)
                           (map #(kotlin-return-content db return-type %) returns)
                           (map #(kotlin-throw-content db %) throws)))
      (if expression-body
        (let [result (emit-kotlin-expression {:db db
                                              :expected-type (some-> return-type type-name)}
                                             expression-body)]
          (-> result
              (with-text (str "            return " (:text result) ";\n"))
              (apply-rule expression-body :kotlin.return-node/to-csharp-return :rule-app.status/success)))
        (emitted (when-let [body-line (kotlin-default-return (or return-type {:type/name "void"}))]
                   (str "            " body-line "\n"))
                 (:decl/source-node function-decl)
                 :kotlin.function-node/to-csharp-stub)))))

(defn- kotlin-function-content [db type-decl function-decl]
  (let [interface? (kotlin-interface? type-decl)
        static? (kotlin-static? db type-decl)
        return-type (:decl/return-type function-decl)
        return-text (if return-type (type-name return-type) "void")
        body-content (kotlin-function-body-content db function-decl return-type)
        param-types (map (comp map-type :source-type)
                         (type-ref-params db function-decl))
        mapped-return (when return-type (map-type return-type))
        text (if interface?
               (str "        " return-text " " (:decl/name function-decl)
                    "(" (param-list db function-decl) ");\n")
               (str "        public " (when static? "static ")
                    return-text " " (:decl/name function-decl)
                    "(" (param-list db function-decl) ")\n"
                    "        {\n"
                    (:text body-content)
                    "        }\n"))]
    (-> body-content
        (apply-type-metadata (cond-> (vec param-types)
                               mapped-return (conj mapped-return)))
        (with-text text)
        (apply-rule (:decl/source-node function-decl)
                    :kotlin.function-node/to-csharp-stub
                    :rule-app.status/success))))

(defn- kotlin-property-content [db type-decl property-decl]
  (let [interface? (kotlin-interface? type-decl)
        static? (kotlin-static? db type-decl)
        property-type (:decl/type property-decl)
        mapped (when property-type (map-type property-type))
        initializer (if (or (kotlin-file-facade? type-decl)
                            (contains? (modifiers property-decl) :override))
                      (kotlin-expression-text (get-in property-decl [:decl/source-node :node/value]))
                      "default!")
        text (if interface?
               (str "        " (or (:csharp/type mapped) "object") " "
                    (:decl/name property-decl)
                    " { get; }\n")
               (str "        public " (when static? "static ")
                    (or (:csharp/type mapped) "object") " "
                    (:decl/name property-decl)
                    " { get; } = " initializer ";\n"))]
    (emitted text
             (:decl/source-node property-decl)
             :kotlin.property-node/to-csharp-stub
             {:usings (:csharp/usings mapped)
              :helpers (:csharp/helpers mapped)
              :diagnostics (:csharp/diagnostics mapped)})))

(defn- kotlin-member-content [db type-decl member]
  (case (:decl/kind member)
    :decl.kind/function (kotlin-function-content db type-decl member)
    :decl.kind/property (kotlin-property-content db type-decl member)
    nil))

(defn- kotlin-declaration-usings [db members]
  (->> members
       (mapcat (fn [member]
                 (concat
                  (keep identity [(:decl/type member) (:decl/return-type member)])
                  (map :source-type (type-ref-params db member)))))
       (mapcat (comp :csharp/usings map-type))
       (map csharp-qualified-name)
       set
       sort
       vec))

(defn- kotlin-type-content [db type-decl]
  (let [namespace (csharp-namespace type-decl)
        members (or (:kotlin.file-facade/members type-decl)
                    (kotlin-member-decls db type-decl))
        member-content (merge-emits "\n" (keep #(kotlin-member-content db type-decl %) members))
        inherited-mappings (when-not (kotlin-file-facade? type-decl)
                             (type-mapping-summary (inherited-types db type-decl)))
        usings (kotlin-declaration-usings db members)
        singleton? (kotlin-singleton-object? db type-decl)
        interface? (kotlin-interface? type-decl)
        type-keyword (cond
                       (kotlin-file-facade? type-decl) "static class"
                       interface? "interface"
                       (kotlin-static? db type-decl) "static class"
                       :else "sealed class")
        singleton-content (when singleton?
                            (str "        public static readonly " (:decl/name type-decl) " Instance = new " (:decl/name type-decl) "();\n\n"
                                 "        private " (:decl/name type-decl) "()\n"
                                 "        {\n"
                                 "        }\n\n"))
        all-usings (->> (concat usings
                                (when-not (kotlin-file-facade? type-decl)
                                  (mapcat :csharp/usings (map map-type (inherited-types db type-decl))))
                                (:usings member-content))
                        (map csharp-qualified-name)
                        (remove #(= namespace %))
                        set
                        sort
                        vec)
        text (str generated-file-header
                  (when (seq all-usings)
                    (str (str/join "\n" (map #(str "using " % ";") all-usings)) "\n\n"))
                  (when-not (str/blank? namespace)
                    (str "namespace " namespace "\n{\n"))
                  "    public " type-keyword " " (:decl/name type-decl) (when-not (kotlin-file-facade? type-decl)
                                                                          (base-list db type-decl)) "\n"
                  "    {\n"
                  singleton-content
                  (:text member-content)
                  (when (seq (:text member-content)) "\n")
                  "    }\n"
                  (when-not (str/blank? namespace)
                    "}\n"))
        rule-id (cond
                  (kotlin-file-facade? type-decl) :kotlin.file-facade/to-csharp-static-class
                  (= :decl.kind/object (:decl/kind type-decl)) :kotlin.object-node/to-csharp-stub
                  :else :kotlin.class-node/to-csharp-stub)
        rule-source-node (if (kotlin-file-facade? type-decl)
                           (or (:decl/source-node (first members))
                               (:decl/source-node type-decl))
                           (:decl/source-node type-decl))]
    (-> member-content
        (apply-type-metadata inherited-mappings)
        (update :usings into all-usings)
        (with-text text)
        (apply-rule rule-source-node
                    rule-id
                    :rule-app.status/success))))

(defn- type-content [db type-decl]
  (case (:decl/lang type-decl)
    :lang/kotlin (kotlin-type-content db type-decl)
    (case (:decl/kind type-decl)
      :decl.kind/annotation (annotation-content db type-decl)
      :decl.kind/enum (enum-content db type-decl)
      :decl.kind/record (record-content db type-decl)
      (class-content db type-decl))))

(defn- helper-output-path [^Path target-dir helper]
  (.resolve target-dir (:helper/path helper)))

(defn- helper-inventory-entry [target-dir helper file]
  (-> helper
      (dissoc :helper/text)
      (assoc :helper/file (slash-path (normalize-path file))
             :helper/project-path (slash-path (.relativize (.normalize target-dir)
                                                           (.normalize (path file)))))))

(defn emit!
  "Regenerate disposable C# declaration skeletons for source declaration facts."
  [db target-dir]
  (let [target-dir (path target-dir)
        classes (source-type-decls db)
        indexes (provenance-indexes db)]
    (clear-directory! target-dir)
    (let [emitted-classes (mapv (fn [class-decl]
                                  (let [file (class-output-path target-dir class-decl)
                                        result (type-content db class-decl)
                                        file-path (slash-path (normalize-path file))
                                        text (:text result)
                                        provenance (finalize-provenance indexes
                                                                        file-path
                                                                        text
                                                                        (:provenance result))]
                                    (write-string! file text)
                                    (assoc result
                                           :dest-file file-path
                                           :provenance provenance
                                           :text nil)))
                                classes)
          files (mapv :dest-file emitted-classes)
          metadata (merge-emits emitted-classes)
          helpers (->> (:helpers metadata)
                       sort
                       (mapv helper-catalog))
          unknown-helpers (->> (:helpers metadata)
                               (remove helper-catalog)
                               sort
                               vec)
          helper-files (mapv (fn [helper]
                               (let [file (helper-output-path target-dir helper)]
                                 (write-string! file (:helper/text helper))
                                 (helper-inventory-entry target-dir helper file)))
                             helpers)
          all-files (vec (concat files (map :helper/file helper-files)))]
      {:csharp/files-written (count all-files)
       :csharp/files all-files
       :csharp/rule-applications (:rule-applications metadata)
       :csharp/provenance (:provenance metadata)
       :csharp/diagnostics (cond-> (:diagnostics metadata)
                              (seq unknown-helpers)
                              (into (mapv (fn [helper-id]
                                            {:diagnostic/severity :diagnostic.severity/error
                                             :diagnostic/message (str "No C# helper source registered for " helper-id)
                                             :helper/id helper-id
                                             :rule/context {:reason :emit.reason/unknown-helper}})
                                          unknown-helpers)))
       :csharp/helpers (vec (sort (:helpers metadata)))
       :csharp/helper-files helper-files
       :csharp/usings (vec (sort (:usings metadata)))})))
