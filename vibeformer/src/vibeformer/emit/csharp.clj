              :where
              [?decl :decl/lang :lang/kotlin]
              [?decl :decl/kind ?kind]
              [(contains? #{:decl.kind/class :decl.kind/interface :decl.kind/object} ?kind)]]
            db)
       (map first)
       (sort-by :decl/qualified-name)
