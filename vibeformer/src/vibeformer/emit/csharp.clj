(defn- path [value]
  (if (instance? Path value)
    value
    (Paths/get (str value) (make-array String 0))))

(defn- slash-path [value]
  (str/replace (str value) \\ \/))

(defn- hex-bytes [bytes]
  (apply str (map #(format "%02x" (bit-and % 0xff)) bytes)))

(defn- sha256 [value]
  (let [bytes (.getBytes (str value) StandardCharsets/UTF_8)]
    (str "sha256:" (hex-bytes (.digest (doto (MessageDigest/getInstance "SHA-256")
                                         (.update bytes)))))))

(defn- normalize-path [value]
  (.normalize (.toAbsolutePath (path value))))

(defn- ensure-dir! [^Path dir]
  (Files/createDirectories dir (make-array java.nio.file.attribute.FileAttribute 0))
  dir)

(defn- clear-directory! [^Path dir]
  (ensure-dir! dir)
  (let [paths (with-open [stream (Files/walk dir (make-array java.nio.file.FileVisitOption 0))]
                (doall (iterator-seq (.iterator stream))))]
    (doseq [entry (sort-by #(count (str %)) > paths)]
      (when-not (= dir entry)
        (Files/deleteIfExists entry)))))

(defn- write-string! [^Path file content]
  (ensure-dir! (.getParent file))
  (Files/writeString file content StandardCharsets/UTF_8 (make-array java.nio.file.OpenOption 0))
  file)

(defn- modifiers [decl]
  (set (:decl/modifiers decl)))

(defn- visibility [mods]
  (cond
    (contains? mods :public) "public"
    (contains? mods :private) "private"
    (contains? mods :protected) "protected"
    :else "internal"))

(defn- simple-name [type-name]
  (some-> type-name
          (str/replace #"\[\]$" "")
          (str/replace #"<.*$" "")
          (str/split #"\.")
          last))

(defn- fallback-type [source-type]
  (let [type-name (:type/name source-type)
        array? (str/ends-with? (or type-name "") "[]")
        base-name (or (simple-name type-name) "object")]
    {:csharp/type (str base-name (when array? "[]"))
     :csharp/usings []
     :csharp/helpers []
     :csharp/diagnostics [(cond-> {:diagnostic/severity :diagnostic.severity/warn
                                    :diagnostic/message (str "No C# type mapping for " type-name
                                                             "; emitted fallback type "
                                                             (str base-name (when array? "[]"))
                                                             ".")
                                    :type/name type-name
                                    :type/lang (:type/lang source-type)
                                    :mapping/reason :mapping.reason/unknown-type
                                    :rule/context {:reason :emit.reason/type-mapping-fallback}}
                             (:type/id source-type)
                             (assoc :type/id (:type/id source-type)))]}))

(defn- map-type [source-type]
  (try
    (type-mapping/map-type source-type)
    (catch clojure.lang.ExceptionInfo ex
      (let [context (select-keys (ex-data ex) [:type/id
                                               :type/lang
                                               :type/name
                                               :type/nullable?
                                               :mapping/reason])]
        (update (fallback-type source-type)
                :csharp/diagnostics
                #(mapv (fn [diagnostic]
                         (merge context diagnostic))
                       %))))))

(defn- mapping-diagnostics [mapped-types]
  (->> mapped-types
       (mapcat :csharp/diagnostics)
       vec))

(defn- mapping-usings [mapped-types]
  (mapcat :csharp/usings mapped-types))

(defn- mapping-helpers [mapped-types]
  (mapcat :csharp/helpers mapped-types))

(defn- apply-type-metadata [result mapped-types]
  (-> result
      (update :usings into (mapping-usings mapped-types))
      (update :helpers into (mapping-helpers mapped-types))
      (update :diagnostics into (mapping-diagnostics mapped-types))))

(defn- type-mapping-summary [source-types]
  (->> source-types
       (map map-type)
       vec))

(defn- type-name [source-type]
  (:csharp/type (map-type source-type)))

